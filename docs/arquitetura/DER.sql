-- DER do Tennis App (MatchPoint) · Etapa 1 · KAN-23 e KAN-24
-- Modelagem: Eduardo e Gabriel Castro. Ajustes para PostgreSQL/Supabase: 23/10/2026.
-- Roda no SQL Editor do Supabase. O login fica no Supabase Auth (auth.users):
-- por isso usuario.id_usuario é uuid e não existe coluna de senha.
-- Os nomes "grupo", "solicitacao_entrada" e "ranking_grupo" ainda dependem de decisão da equipe.

CREATE TABLE usuario (
  id_usuario uuid PRIMARY KEY REFERENCES auth.users (id) ON DELETE CASCADE,
  nome varchar(100) NOT NULL,
  email varchar(150) UNIQUE NOT NULL,
  telefone varchar(20),
  tipo_usuario varchar(20) NOT NULL CHECK (tipo_usuario IN ('PROFESSOR', 'ALUNO')),
  status_conta varchar(20) NOT NULL DEFAULT 'ATIVA' CHECK (status_conta IN ('ATIVA', 'INATIVA'))
);

CREATE TABLE grupo (
  id_grupo int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_professor uuid NOT NULL REFERENCES usuario (id_usuario),
  nome varchar(100) NOT NULL,
  descricao text,
  data_criacao timestamptz NOT NULL DEFAULT now(),
  status varchar(20) NOT NULL DEFAULT 'ATIVO' CHECK (status IN ('ATIVO', 'INATIVO'))
);

CREATE TABLE grupo_aluno (
  id_grupo_aluno int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_grupo int NOT NULL REFERENCES grupo (id_grupo),
  id_aluno uuid NOT NULL REFERENCES usuario (id_usuario),
  nivel varchar(50),
  data_entrada timestamptz NOT NULL DEFAULT now(),
  status varchar(20) NOT NULL DEFAULT 'ATIVO' CHECK (status IN ('ATIVO', 'SAIU')),
  UNIQUE (id_grupo, id_aluno)
);

CREATE TABLE aula (
  id_aula int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_grupo int NOT NULL REFERENCES grupo (id_grupo),
  titulo varchar(100),
  conteudo text,
  data_hora_inicio timestamptz NOT NULL,
  data_hora_fim timestamptz,
  local varchar(150),
  limite_alunos int NOT NULL DEFAULT 6 CHECK (limite_alunos BETWEEN 1 AND 6), -- RN07
  status varchar(20) NOT NULL DEFAULT 'AGENDADA' CHECK (status IN ('AGENDADA', 'REALIZADA', 'CANCELADA')),
  CHECK (data_hora_fim IS NULL OR data_hora_fim > data_hora_inicio)
);

CREATE TABLE presenca (
  id_presenca int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_aula int NOT NULL REFERENCES aula (id_aula),
  id_aluno uuid NOT NULL REFERENCES usuario (id_usuario),
  status varchar(30) NOT NULL CHECK (status IN ('CONFIRMADA', 'PENDENTE', 'PRESENTE', 'AUSENTE', 'CANCELADA')),
  data_confirmacao timestamptz,
  data_registro_professor timestamptz,
  motivo_cancelamento text,
  UNIQUE (id_aula, id_aluno)
);

CREATE TABLE convite_grupo (
  id_convite int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_grupo int NOT NULL REFERENCES grupo (id_grupo),
  codigo varchar(6) UNIQUE NOT NULL,
  data_criacao timestamptz NOT NULL DEFAULT now(),
  data_expiracao timestamptz NOT NULL, -- RN01: 7 dias
  status varchar(20) NOT NULL DEFAULT 'ATIVO' CHECK (status IN ('ATIVO', 'EXPIRADO', 'REVOGADO')),
  CHECK (data_expiracao > data_criacao)
);

CREATE TABLE solicitacao_entrada (
  id_solicitacao int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_grupo int NOT NULL REFERENCES grupo (id_grupo),
  id_aluno uuid NOT NULL REFERENCES usuario (id_usuario),
  data_solicitacao timestamptz NOT NULL DEFAULT now(),
  data_limite_aceite timestamptz,
  data_resposta timestamptz,
  status varchar(20) NOT NULL DEFAULT 'PENDENTE' CHECK (status IN ('PENDENTE', 'ACEITA', 'RECUSADA', 'EXPIRADA'))
);

CREATE TABLE partida (
  id_partida int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_grupo int NOT NULL REFERENCES grupo (id_grupo),
  id_jogador1 uuid NOT NULL REFERENCES usuario (id_usuario),
  id_jogador2 uuid NOT NULL REFERENCES usuario (id_usuario),
  id_registrador uuid NOT NULL REFERENCES usuario (id_usuario),
  id_vencedor uuid REFERENCES usuario (id_usuario),
  id_validador uuid REFERENCES usuario (id_usuario),
  data_partida timestamptz,
  data_registro timestamptz NOT NULL DEFAULT now(),
  data_confirmacao timestamptz,
  status varchar(30) NOT NULL DEFAULT 'PENDENTE' CHECK (status IN ('DESAFIADA', 'PENDENTE', 'CONFIRMADA', 'CONTESTADA', 'VALIDADA')),
  pontuacao_jogador1 int CHECK (pontuacao_jogador1 >= 0),
  pontuacao_jogador2 int CHECK (pontuacao_jogador2 >= 0),
  CHECK (id_jogador1 <> id_jogador2),
  CHECK (id_vencedor IS NULL OR id_vencedor IN (id_jogador1, id_jogador2))
);

CREATE TABLE partida_set (
  id_set int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_partida int NOT NULL REFERENCES partida (id_partida) ON DELETE CASCADE,
  numero_set int NOT NULL CHECK (numero_set BETWEEN 1 AND 5),
  games_jogador1 int NOT NULL CHECK (games_jogador1 >= 0),
  games_jogador2 int NOT NULL CHECK (games_jogador2 >= 0),
  UNIQUE (id_partida, numero_set)
);

CREATE TABLE fundamento (
  id_fundamento int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome varchar(100) UNIQUE NOT NULL,
  descricao text
);

CREATE TABLE avaliacao_fundamento (
  id_avaliacao int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_grupo_aluno int NOT NULL REFERENCES grupo_aluno (id_grupo_aluno),
  id_fundamento int NOT NULL REFERENCES fundamento (id_fundamento),
  id_professor uuid NOT NULL REFERENCES usuario (id_usuario),
  nota decimal(4,2) NOT NULL CHECK (nota BETWEEN 1 AND 5),
  comentario text,
  data_avaliacao timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE anotacao_aula (
  id_anotacao int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_aluno uuid NOT NULL REFERENCES usuario (id_usuario),
  id_aula int NOT NULL REFERENCES aula (id_aula),
  texto text NOT NULL,
  data_criacao timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE atividade (
  id_atividade int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_aula int NOT NULL REFERENCES aula (id_aula),
  titulo varchar(100) NOT NULL,
  descricao text,
  data_limite timestamptz,
  tipo varchar(30)
);

CREATE TABLE entrega_atividade (
  id_entrega int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_atividade int NOT NULL REFERENCES atividade (id_atividade),
  id_aluno uuid NOT NULL REFERENCES usuario (id_usuario),
  arquivo_url varchar(500),
  resposta_texto text,
  data_entrega timestamptz NOT NULL DEFAULT now(),
  feedback_professor text,
  status varchar(30) NOT NULL DEFAULT 'ENTREGUE' CHECK (status IN ('ENTREGUE', 'AVALIADA')),
  CHECK (arquivo_url IS NOT NULL OR resposta_texto IS NOT NULL)
);

CREATE TABLE comentario_aula (
  id_comentario int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_aula int NOT NULL REFERENCES aula (id_aula),
  id_professor uuid NOT NULL REFERENCES usuario (id_usuario),
  texto text NOT NULL,
  data_criacao timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE desafio (
  id_desafio int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_aluno_desafiante uuid NOT NULL REFERENCES usuario (id_usuario),
  id_aluno_desafiado uuid NOT NULL REFERENCES usuario (id_usuario),
  id_grupo int NOT NULL REFERENCES grupo (id_grupo),
  data_desafio timestamptz NOT NULL DEFAULT now(),
  data_resposta timestamptz,
  status varchar(20) NOT NULL DEFAULT 'PENDENTE' CHECK (status IN ('PENDENTE', 'ACEITO', 'RECUSADO', 'EXPIRADO')),
  id_partida int REFERENCES partida (id_partida),
  CHECK (id_aluno_desafiante <> id_aluno_desafiado) -- RN04: mesmo grupo
);

CREATE TABLE ranking_grupo (
  id_ranking int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_grupo int NOT NULL REFERENCES grupo (id_grupo),
  id_aluno uuid NOT NULL REFERENCES usuario (id_usuario),
  pontos int NOT NULL DEFAULT 0 CHECK (pontos >= 0),
  vitorias int NOT NULL DEFAULT 0 CHECK (vitorias >= 0),
  derrotas int NOT NULL DEFAULT 0 CHECK (derrotas >= 0),
  atualizado_em timestamptz,
  UNIQUE (id_grupo, id_aluno)
);

-- RF25: alertas e notificações
CREATE TABLE notificacao (
  id_notificacao int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_usuario uuid NOT NULL REFERENCES usuario (id_usuario) ON DELETE CASCADE,
  tipo varchar(30) NOT NULL CHECK (tipo IN ('AULA', 'PRESENCA', 'CONVITE', 'DESAFIO', 'PARTIDA', 'AVALIACAO', 'ATIVIDADE')),
  mensagem text NOT NULL,
  lida boolean NOT NULL DEFAULT false,
  data_criacao timestamptz NOT NULL DEFAULT now()
);
